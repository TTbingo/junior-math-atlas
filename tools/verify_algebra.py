checks = []


def ck(name, got, want):
    try:
        ok = (got == want)
        if not ok and isinstance(got, (int, float)) and isinstance(want, (int, float)):
            ok = abs(got - want) < 1e-9
    except Exception:
        ok = False
    checks.append((bool(ok), name, got, want))


