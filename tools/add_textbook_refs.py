def main():
    applied = 0
    for f in sorted(C.glob("*.json")):
        d = json.loads(f.read_text(encoding="utf-8"))
        pid = d["id"]
        if pid not in LOC:
            print(f"!! 未定位: {pid}")
            continue
        vol, ch, secs, note = LOC[pid]
        d["textbook_ref"] = {
            "volume": vol,
            "chapter": ch,
            "sections": secs,
            "note": note,
        }
        f.write_text(json.dumps(d, ensure_ascii=False, indent=2), encoding="utf-8")
        applied += 1
    print(f"已标注 {applied} 篇")


if __name__ == "__main__":
    main()
