# 禁用词：与 content/taxonomy.json 的 forbidden_words 保持一致
FORBIDDEN = ("显然", "易证", "不难看出")


def repair(pid, steps):
    """修掉历史编码损坏（只影响 m3-02-03 的一处 U+FFFD）。"""
    fixes = MOJIBAKE_REPAIRS.get(pid, [])
    out = []
    for s in steps:
        for bad, good in fixes:
            s = s.replace(bad, good)
        out.append(s)
    return out


def load_original():
    """取回原始 steps（字符串列表）。有备份用备份，无备份则从现文件读。"""
    if ORIG_FILE.exists():
        return json.loads(ORIG_FILE.read_text(encoding="utf-8"))
    out = {}
    for pid in STEPS:
        d = json.loads((C / f"{pid}.json").read_text(encoding="utf-8"))
        st = d["sections"]["why"]["steps"]
        if st and isinstance(st[0], dict):
            out[pid] = [s["proof"] for s in st]
        else:
            out[pid] = repair(pid, st)
    return out


def save_original(orig):
    ORIG_FILE.write_text(
        json.dumps(orig, ensure_ascii=False, indent=2), encoding="utf-8")


def main(dry_run=False):
    orig = load_original()
    assert set(orig) == set(STEPS), "备份与新内容篇目不一致"
    if not ORIG_FILE.exists() and not dry_run:
        save_original(orig)

    problems = []
    total = 0
    for pid, items in STEPS.items():
        old = orig[pid]
        heads = HEADERS[pid]
        if len(old) != len(items):
            problems.append(f"{pid}: 原 {len(old)} 步，新 {len(items)} 条，条数必须一一对应")
            continue
        if len(heads) != len(items):
            problems.append(f"{pid}: 标签数 {len(heads)} 与条数 {len(items)} 不符")
            continue

        steps = []
        for i, (o, it) in enumerate(zip(old, items), 1):
            head = heads[i - 1]
            body = o
            if head:
                if not o.startswith(head):
                    problems.append(f"{pid}[{i}]: 原文不以标签「{head}」开头")
                    continue
                body = o[len(head):]
            if not body.strip():
                problems.append(f"{pid}[{i}]: 标签之后正文为空")
                continue
            steps.append({
                "conclusion": it["conclusion"],
                # proof 按原文切片构造，逐字保留，不做任何改写
                "proof": body,
                "key": it["key"],
            })

        # 字段级规矩
        for i, s in enumerate(steps, 1):
            if set(s) != {"conclusion", "proof", "key"}:
                problems.append(f"{pid}[{i}]: 字段必须正好是三项")
                continue
            if not all(v.strip() for v in s.values()):
                problems.append(f"{pid}[{i}]: 存在空字段")
                continue
            for k, v in s.items():
                if v.startswith("结论 "):
                    problems.append(f"{pid}[{i}].{k}: 不要写编号前缀")
                if "关键一步：" in v:
                    problems.append(f"{pid}[{i}].{k}: 不要重复渲染层的标签")
                for w in FORBIDDEN:
                    if w in v:
                        problems.append(f"{pid}[{i}].{k}: 命中跳步话术「{w}」")
                if v.count("$") % 2:
                    problems.append(f"{pid}[{i}].{k}: $ 不成对（{v.count('$')} 个）")

        # 全文数学内容核对：原文出现的每一个公式都必须出现在新 proof 里
        for i, (o, s) in enumerate(zip(old, steps), 1):
            import re
            for f in re.findall(r"\$([^$]+)\$", o):
                if f not in s["proof"]:
                    problems.append(f"{pid}[{i}]: 公式 ${f}$ 未原样保留在 proof 中")

        if problems:
            continue

        total += len(steps)
        if not dry_run:
            path = C / f"{pid}.json"
            d = json.loads(path.read_text(encoding="utf-8"))
            d["sections"]["why"]["steps"] = steps
            # 保持与原文件相同的字节风格：CRLF 换行、末尾不带换行
            text = json.dumps(d, ensure_ascii=False, indent=2).replace("\n", "\r\n")
            path.write_bytes(text.encode("utf-8"))
        print(f"{pid}: {len(steps)} 条结论" + ("（dry-run，未写盘）" if dry_run else ""))

    if problems:
        print(f"\n✗ {len(problems)} 条问题：")
        for p in problems:
            print("  ✗", p)
        return 1
    print(f"\n共 {len(STEPS)} 篇、{total} 条结论")
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.exit(main(dry_run="--dry-run" in sys.argv))
